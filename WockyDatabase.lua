---------------------------------------------------------------------------
-- Race routes. Every Warlock race gets its own start, then joins its faction route.
-- {CLASSHUB} is replaced by the race's warlock trainer place for the class quests.
---------------------------------------------------------------------------
local function Q(quest, place, zone, x, y)
    return { quest = quest, npc = place, zone = zone, x = x, y = y }
end

local function Build(base, from, to, extra)
    local out = {}
    if base then
        for lvl = from, to do
            local e = base["L" .. lvl]
            if e then out["L" .. lvl] = e end
        end
    end
    for k, v in pairs(extra or {}) do out[k] = v end
    return out
end

local function WithHub(src, hubText, hubPlace, hubZone, hx, hy)
    local out = {}
    for k, e in pairs(src) do
        local quest = string.gsub(e.quest, "{CLASSHUB}", hubText)
        if e.npc == "{CLASSHUB}" then
            out[k] = Q(quest, hubPlace, hubZone, hx, hy)
        else
            out[k] = Q(quest, e.npc, e.zone, e.x, e.y)
        end
    end
    return out
end

